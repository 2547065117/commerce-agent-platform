package com.ecommerce.portal;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.annotation.PostConstruct;
import java.nio.file.*;
import java.security.SecureRandom;
import java.time.Instant;
import java.util.*;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Repository;

@Repository
public class PortalStore {
    private final JdbcTemplate db;
    private final ObjectMapper json;
    private final PasswordEncoder passwords;
    @Value("${portal.admin-password:}") private String initialPassword;
    @Value("${portal.credentials-file:./data/initial-admin.txt}") private String credentialsFile;
    public PortalStore(JdbcTemplate db, ObjectMapper json, PasswordEncoder passwords) {
        this.db = db; this.json = json; this.passwords = passwords;
    }
    @PostConstruct void init() throws Exception {
        db.execute("CREATE TABLE IF NOT EXISTS portal_users (username VARCHAR(80) PRIMARY KEY, password_hash VARCHAR(200) NOT NULL, role VARCHAR(20) NOT NULL)");
        db.execute("CREATE TABLE IF NOT EXISTS recommendation_runs (id VARCHAR(36) PRIMARY KEY, username VARCHAR(80), user_id VARCHAR(100), scene VARCHAR(40), status VARCHAR(20), duration_ms BIGINT, created_at VARCHAR(40), request_json CLOB, response_json CLOB, error VARCHAR(500))");
        db.execute("CREATE TABLE IF NOT EXISTS audit_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(80), action VARCHAR(100), detail VARCHAR(500), created_at VARCHAR(40))");
        if (db.queryForObject("SELECT COUNT(*) FROM portal_users", Integer.class) == 0) {
            String password = initialPassword;
            if (password.isBlank()) {
                byte[] bytes = new byte[18]; new SecureRandom().nextBytes(bytes);
                password = Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
            }
            if (password.length() < 12) throw new IllegalStateException("PORTAL_ADMIN_PASSWORD must contain at least 12 characters");
            db.update("INSERT INTO portal_users VALUES (?,?,?)", "admin", passwords.encode(password), "ADMIN");
            Path file = Path.of(credentialsFile); Files.createDirectories(file.toAbsolutePath().getParent());
            Files.writeString(file, "username=admin\npassword=" + password + "\n");
            audit("system", "SYSTEM_INITIALIZED", "Initial administrator created");
        }
    }
    public List<Map<String,Object>> user(String username) {
        return db.queryForList("SELECT username, password_hash, role FROM portal_users WHERE username=?", username);
    }
    public void audit(String username, String action, String detail) {
        db.update("INSERT INTO audit_events(username,action,detail,created_at) VALUES(?,?,?,?)", username, action, detail, Instant.now().toString());
    }
    public void save(String id, String actor, String user, String scene, String status, long duration, Object request, Object response, String error) {
        db.update("INSERT INTO recommendation_runs(id,username,user_id,scene,status,duration_ms,created_at,request_json,response_json,error) VALUES(?,?,?,?,?,?,?,?,?,?)", id, actor, user, scene, status, duration, Instant.now().toString(), encode(request), encode(response), error);
    }
    public List<Map<String,Object>> runs() {
        return db.query("SELECT id,username,user_id,scene,status,duration_ms,created_at FROM recommendation_runs ORDER BY created_at DESC LIMIT 100",
            (rs,n) -> Map.of("id",rs.getString(1),"username",rs.getString(2),"user_id",rs.getString(3),"scene",rs.getString(4),"status",rs.getString(5),"duration_ms",rs.getLong(6),"created_at",rs.getString(7)));
    }
    public Map<String,Object> run(String id) {
        return db.query("SELECT request_json,response_json,error,status FROM recommendation_runs WHERE id=?", rs -> {
            if (!rs.next()) return null;
            Map<String,Object> result = new LinkedHashMap<>();
            result.put("request", decode(rs.getString(1))); result.put("response", decode(rs.getString(2)));
            result.put("error",rs.getString(3)); result.put("status",rs.getString(4)); return result;
        }, id);
    }
    public List<Map<String,Object>> auditEvents() {
        return db.query("SELECT username,action,detail,created_at FROM audit_events ORDER BY id DESC LIMIT 100",
            (rs,n) -> Map.of("username",rs.getString(1),"action",rs.getString(2),"detail",rs.getString(3),"created_at",rs.getString(4)));
    }
    public Map<String,Object> stats() {
        return db.queryForMap("SELECT COUNT(*) AS total, COALESCE(SUM(CASE WHEN status='SUCCESS' THEN 1 ELSE 0 END),0) AS successful, COALESCE(SUM(CASE WHEN status='DEGRADED' THEN 1 ELSE 0 END),0) AS degraded, COALESCE(AVG(duration_ms),0) AS avg_duration_ms FROM recommendation_runs");
    }
    public List<Map<String,Object>> products() {
        Map<String,Map<String,Object>> products = new TreeMap<>();
        List<String> payloads = db.queryForList("SELECT response_json FROM recommendation_runs WHERE status<>'FAILED' ORDER BY created_at ASC", String.class);
        for (String payload : payloads) {
            Map<String,Object> response = decode(payload);
            Object items = response.get("products");
            if (items instanceof List<?> list) for (Object item : list) {
                Map<String,Object> product = json.convertValue(item, new TypeReference<>() {});
                products.put(String.valueOf(product.get("product_id")), product);
            }
        }
        return new ArrayList<>(products.values());
    }
    private String encode(Object value) { try { return json.writeValueAsString(value); } catch (Exception e) { throw new IllegalStateException("JSON serialization failed", e); } }
    private Map<String,Object> decode(String value) { try { return value == null || value.equals("null") ? Map.of() : json.readValue(value, new TypeReference<>() {}); } catch (Exception e) { throw new IllegalStateException("Stored JSON is invalid", e); } }
}
